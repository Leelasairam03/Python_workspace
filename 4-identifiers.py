#rules for identifiers
#1. identifiers can be a combination of letters in lowercase (a to z) or uppercase (A to Z) or digits (0 to 9) or an underscore (_) character.
#2. identifiers cannot start with a digit (0 to 9).
#3. keywords cannot be used as identifiers.
#4. identifiers can be of any length.
#5. identifiers are case sensitive.
#6. identifiers cannot contain special characters like !, @, #, $, %, ^, &, *, (, ), -, +, =, {, }, [, ], |, \, :, ;, ", ', <, >, ,, ., ?, /.
#7. identifiers cannot contain spaces.
